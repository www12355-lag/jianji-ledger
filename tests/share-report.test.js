const assert=require('node:assert/strict');
const {period,summarize,comparison}=require('../share-report.js');
const entries=[{id:1,type:'expense',date:'2026-10-12',amount:100,category:'餐饮',splits:[{category:'餐饮',amount:40},{category:'购物',amount:60}],merchant:'PRIVATE',note:'SECRET',accountId:'PRIVATE'}, {id:2,type:'refund',date:'2026-10-13',amount:10,category:'餐饮',refundOf:1}, {id:3,type:'income',date:'2026-10-13',amount:200}, {id:4,type:'excluded',date:'2026-10-13',amount:500}, {id:5,type:'expense',date:'2026-10-14',amount:9999,category:'餐饮'}, {id:6,type:'expense',date:'2026-10-12',amount:9999,category:'餐饮',deletedAt:'today'}];
const week=period('week','2026-10-13','2026-10-13');
assert.deepEqual(week,{mode:'week',start:'2026-10-12',end:'2026-10-18',through:'2026-10-13',incomplete:true,label:'周报'});
assert.equal(period('week','2026-01-01','2026-01-01').start,'2025-12-29');
assert.equal(period('month','2024-02-10','2024-03-01').end,'2024-02-29');
assert.throws(()=>period('day','2026-10-14','2026-10-13'),/不能晚于今天/);
assert.throws(()=>period('day','2026-02-30'),/有效/);
const s=summarize(entries,week);
assert.equal(s.income,200);assert.equal(s.net,90);assert.equal(s.balance,110);assert.equal(s.refunds,10);assert.equal(s.count,3);assert.equal(s.recordedDays,2);assert.equal(s.daysWithoutRecordedExpense,1);
assert.deepEqual(s.categories,[{category:'购物',total:60,percent:67},{category:'餐饮',total:30,percent:33}]);
assert.equal(JSON.stringify(s).includes('PRIVATE'),false);assert.equal(JSON.stringify(s).includes('SECRET'),false);
assert.equal(comparison(entries,week,s),'本期进行中，先记录当下');
const day=period('day','2026-10-13','2026-10-13'), d=summarize(entries,day);
assert.equal(d.net,-10);assert.equal(d.balance,210);assert.equal(d.negativeCategories,1);
assert.equal(comparison(entries,day,d),'有退款抵扣，本期不计算变化比例');
assert.equal(summarize([],day).title,'故事待续');
const fullWeek=period('week','2026-10-05','2026-10-13');
assert.equal(comparison([],fullWeek,summarize([],fullWeek)),'上一期未记账，暂不比较');
const decimal=summarize([{type:'expense',date:'2026-10-13',amount:0.1,category:'餐饮'},{type:'expense',date:'2026-10-13',amount:0.2,category:'餐饮'}],day);
assert.equal(decimal.net,0.3);
console.log('Share report period boundaries, privacy, splits, refunds and cents: passed');
